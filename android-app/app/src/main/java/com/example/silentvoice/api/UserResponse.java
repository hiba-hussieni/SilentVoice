package com.example.silentvoice.api;

public class UserResponse {

    private int id;
    private String fullName;
    private String email;
    private String phone;

    public int getId() {
        return id;
    }

    public String getFullName() {
        return fullName;
    }

    public String getEmail() {
        return email;
    }

    public String getPhone() {
        return phone;
    }
}